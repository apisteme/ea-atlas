#!/usr/bin/env python3
"""Builds the Microsoft Copilot (Copilot Studio and Agent Builder) skill package from this repository.

    python3 tools/make_copilot_skill.py [--out dist/copilot-studio]

Writes two zips with the same content:
  enterprise-architecture-atlas.zip         SKILL.md at the top level of the zip (try this first)
  enterprise-architecture-atlas-folder.zip  everything inside an enterprise-architecture-atlas/ folder
and checks them against the published skill package limits: allowed file types, folder depth 3,
350 files, 25 MB a file, 50 MB a zip, instructions under 20,000 characters, UTF-8 without BOM.
"""
import argparse, json, os, re, shutil, subprocess, sys, tempfile, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILL = os.path.join(ROOT, "plugins", "enterprise-architecture-atlas", "skills", "enterprise-architecture-atlas")
NAME = "enterprise-architecture-atlas"
ALLOWED = {".json", ".xml", ".yaml", ".yml", ".ini", ".config", ".utf8", ".docx", ".doc", ".docm", ".pdf", ".txt", ".rtf", ".md", ".ppt", ".pptx",
           ".ppsm", ".xlsx", ".xls", ".xlsm", ".csv", ".tsv", ".html", ".htm", ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".log",
           ".py", ".js", ".mjs", ".cjs", ".ts", ".mts", ".sh", ".bash"}
SCRIPTS = ["build.py", "build_data.py", "build_xlsx.py", "build_dashboard.py", "mini_xlsx.py", "impact_engine.py", "taxonomy.py", "diff_snapshots.py",
           "pack_tools.py", "atlas_bundle.py", "check_env.py"]
# Tenants may block .js and .html uploads, so the package holds only Python, JSON, XML and Markdown. The dashboard page,
# with its JavaScript inlined, is stored as a Python string in scripts/dashboard_page.py.
BLOCKED = {".js", ".mjs", ".cjs", ".ts", ".mts", ".html", ".htm", ".sh", ".bash"}

ap = argparse.ArgumentParser()
ap.add_argument("--out", default=os.path.join(ROOT, "dist", "copilot-studio"))
a = ap.parse_args()
OUT = os.path.abspath(a.out)
stage = os.path.join(OUT, NAME)
shutil.rmtree(stage, ignore_errors=True)
os.makedirs(os.path.join(stage, "scripts"))

# SKILL.md
shutil.copy(os.path.join(ROOT, "kits", "copilot-studio", "SKILL.md"), os.path.join(stage, "SKILL.md"))
# scripts
for f in SCRIPTS:
    shutil.copy(os.path.join(SKILL, "engine", f), os.path.join(stage, "scripts", f))
shutil.copy(os.path.join(SKILL, "importers", "archimate_import.py"), os.path.join(stage, "scripts", "archimate_import.py"))
sys.path.insert(0, os.path.join(SKILL, "engine"))
import build_dashboard as _bd
_page = _bd.page_template()
assert "/*__" not in _page and "__DATA__" in _page and "__TITLE__" in _page
open(os.path.join(stage, "scripts", "dashboard_page.py"), "w", encoding="utf-8").write(
    '"""The atlas dashboard page: HTML, CSS and JavaScript as one string, generated by tools/make_copilot_skill.py from\n'
    'engine/dashboard_template.html and the engine .js modules. build_dashboard.py fills in __TITLE__ and __DATA__.\n'
    'It is stored in a .py file because some tenants do not accept .js or .html files in a skill package. Do not edit by hand."""\n'
    "TEMPLATE = " + repr(_page) + "\n")
p = os.path.join(stage, "scripts", "build_dashboard.py")
t = open(p, encoding="utf-8").read()
assert 'ASSISTANT = "Claude"' in t and 'HOST = "workspace"' in t
open(p, "w", encoding="utf-8").write(t.replace('ASSISTANT = "Claude"', 'ASSISTANT = "Copilot"').replace('HOST = "workspace"', 'HOST = "chat"'))
# packs
shutil.copytree(os.path.join(SKILL, "packs"), os.path.join(stage, "packs"), ignore=shutil.ignore_patterns("__pycache__"))
# references, adapted for a host without Claude artifacts or Claude skills
os.makedirs(os.path.join(stage, "references"))
for f in ("model-schema.md", "pack-authoring.md", "outputs.md"):
    t = open(os.path.join(SKILL, "reference", f), encoding="utf-8").read().replace("engine/", "scripts/")
    if f == "outputs.md":
        t = re.sub(r"One self-contained HTML page: .*?\n", "One self-contained HTML page: `output/<prefix>_EA_Dashboard.html`. It works offline and can be shared as a file or put on an intranet or SharePoint. `repository/atlas_page.html` is the same page without its document wrapper, for hosts that publish pages.\n", t, count=1)
        t = t.replace("Saved scenarios use the artifact `db` capability with `user` for authorship, falling back to browser storage.", "Saved scenarios are kept in the viewer's browser storage.")
        t = t.replace("saved features use the `features` db collection (browser storage in the standalone file)", "saved features are kept in the viewer's browser storage")
        t = re.sub(r"Recalculate with the xlsx skill's `recalc.py` \(pass it to `build.py --recalc`\) and check for zero formula errors\.", "Excel recalculates every formula when the file is opened.", t)
        t = re.sub(r"\n## Copilot kit \(optional\).*?(?=\n## )", "\n", t, flags=re.S)
        t = re.sub(r"\n## Prompt file.*\Z", "\n", t, flags=re.S)
    open(os.path.join(stage, "references", f), "w", encoding="utf-8").write(t)
notice = open(os.path.join(ROOT, "NOTICE.md"), encoding="utf-8").read().replace("`samples/archisurance/Archisurance.archimate`", "`assets/Archisurance.archimate.xml`").replace("`samples/archisurance/LICENSE-Archi.txt`", "`assets/LICENSE-Archi.txt`")
lic = open(os.path.join(ROOT, "LICENSE"), encoding="utf-8").read()
content = open(os.path.join(ROOT, "LICENSE-CONTENT.md"), encoding="utf-8").read()
open(os.path.join(stage, "references", "licence-and-notices.md"), "w", encoding="utf-8").write(content + "\n## MIT licence (source code)\n\n```\n" + lic + "```\n\n" + notice)
# assets: example atlas file (built so it carries a release snapshot) and the Archi model
os.makedirs(os.path.join(stage, "assets"))
shutil.copy(os.path.join(SKILL, "samples", "archisurance", "Archisurance.archimate"), os.path.join(stage, "assets", "Archisurance.archimate.xml"))
shutil.copy(os.path.join(SKILL, "samples", "archisurance", "LICENSE-Archi.txt"), os.path.join(stage, "assets", "LICENSE-Archi.txt"))
tmp = tempfile.mkdtemp()
ws = os.path.join(tmp, "ws")
shutil.copytree(os.path.join(SKILL, "samples", "archisurance", "model"), os.path.join(ws, "model"))
r = subprocess.run([sys.executable, os.path.join(stage, "scripts", "build.py"), "--workspace", ws, "--engine", "python", "--skip-xlsx"], capture_output=True, text=True)
if r.returncode:
    sys.exit("Example build failed:\n" + r.stdout[-2000:] + r.stderr[-2000:])
subprocess.run([sys.executable, os.path.join(stage, "scripts", "atlas_bundle.py"), "pack", "--workspace", ws, "--out", os.path.join(stage, "assets", "archisurance_atlas_model.json")], check=True)
shutil.rmtree(tmp, ignore_errors=True)
for d, _, fs in os.walk(stage):
    if os.path.basename(d) == "__pycache__":
        shutil.rmtree(d)

# ---------------------------------------------------------------- checks
problems = []
files = []
for d, _, fs in os.walk(stage):
    for f in fs:
        p = os.path.join(d, f)
        rel = os.path.relpath(p, stage)
        files.append(rel)
        ext = os.path.splitext(f)[1].lower()
        if ext not in ALLOWED:
            problems.append(f"file type not allowed: {rel}")
        if ext in BLOCKED:
            problems.append(f"file type often blocked by tenants: {rel}")
        if os.path.getsize(p) > 25 * 1024 * 1024:
            problems.append(f"over 25 MB: {rel}")
        depth = rel.count(os.sep) + 1  # folders above the file, counting the wrapper folder
        if depth > 3:
            problems.append(f"too deep for the folder zip: {rel}")
if len(files) > 350:
    problems.append(f"{len(files)} files (limit 350)")
raw = open(os.path.join(stage, "SKILL.md"), "rb").read()
if raw.startswith(b"\xef\xbb\xbf"):
    problems.append("SKILL.md has a byte-order mark")
txt = raw.decode("utf-8")
m = re.match(r"^---\n(.*?)\n---\n(.*)\Z", txt, re.S)
if not m:
    problems.append("SKILL.md frontmatter missing")
else:
    fm, body = m.group(1), m.group(2)
    try:
        import yaml
        meta = yaml.safe_load(fm)
    except ImportError:
        meta = dict(re.findall(r'^(\w[\w-]*):\s*"?(.*?)"?$', fm, re.M))
    if meta.get("name") != NAME:
        problems.append("name does not match the folder name")
    if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", meta.get("name", "")) or len(meta.get("name", "")) > 64:
        problems.append("name breaks the naming rules")
    desc = meta.get("description", "")
    if not desc or "\n" in desc or len(desc) > 1024:
        problems.append(f"description must be one line of 1 to 1024 characters (now {len(desc)})")
    if len(body) >= 20000:
        problems.append(f"instructions are {len(body)} characters (limit 20,000)")
    if "—" in txt or "–" in txt:
        problems.append("SKILL.md contains em or en dashes")
    if re.search(r"(?i)\bartifact\b|claude", body):
        problems.append("SKILL.md mentions Claude-specific features")
for rel in files:
    if rel.endswith((".md", ".py", ".js", ".html", ".json")):
        t = open(os.path.join(stage, rel), encoding="utf-8", errors="ignore").read()
        if re.search(r"(?i)\bptsb\b|permanent tsb|bawag|kyndryl", t):
            problems.append(f"client reference in {rel}")
        if rel != os.path.join("references", "licence-and-notices.md") and re.search(r"(?i)claude", re.sub(r"window\.claude", "", t)):
            problems.append(f"mentions Claude: {rel}")

# ---------------------------------------------------------------- zips
z1 = os.path.join(OUT, f"{NAME}.zip")
z2 = os.path.join(OUT, f"{NAME}-folder.zip")
for z, prefix in ((z1, ""), (z2, NAME + "/")):
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for rel in sorted(files):
            zf.write(os.path.join(stage, rel), prefix + rel.replace(os.sep, "/"))
    if os.path.getsize(z) > 50 * 1024 * 1024:
        problems.append(f"{os.path.basename(z)} over 50 MB")
print(f"Staged {len(files)} files in {stage}")
print(f"SKILL.md instructions: {len(body)} characters; description {len(desc)} characters")
for z in (z1, z2):
    print(f"{z}  {os.path.getsize(z) // 1024} KB")
print("Checks:", "all passed" if not problems else "")
for p in problems:
    print("  PROBLEM", p)
sys.exit(1 if problems else 0)
